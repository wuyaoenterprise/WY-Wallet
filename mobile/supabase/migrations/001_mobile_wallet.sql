create or replace function public.wallet_touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists wallet_profiles_touch_updated_at on public.wallet_profiles;
create trigger wallet_profiles_touch_updated_at
before update on public.wallet_profiles
for each row execute function public.wallet_touch_updated_at();

drop trigger if exists wallet_transactions_touch_updated_at on public.wallet_transactions;
create trigger wallet_transactions_touch_updated_at
before update on public.wallet_transactions
for each row execute function public.wallet_touch_updated_at();

create or replace function public.wallet_seed_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.wallet_profiles(user_id, display_name, email, avatar_url)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'full_name', new.raw_user_meta_data->>'name', split_part(coalesce(new.email, ''), '@', 1)),
    new.email,
    new.raw_user_meta_data->>'avatar_url'
  )
  on conflict (user_id) do update set
    display_name = excluded.display_name,
    email = excluded.email,
    avatar_url = excluded.avatar_url;

  insert into public.wallet_categories(user_id, name)
  select new.id, category
  from unnest(array['饮食','交通','购物','居住','娱乐','医疗','教育','投资','旅游','其他']) as category
  on conflict (user_id, name) do nothing;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created_wallet on auth.users;
create trigger on_auth_user_created_wallet
after insert on auth.users
for each row execute function public.wallet_seed_user();

insert into public.wallet_profiles(user_id, display_name, email, avatar_url)
select
  id,
  coalesce(raw_user_meta_data->>'full_name', raw_user_meta_data->>'name', split_part(coalesce(email, ''), '@', 1)),
  email,
  raw_user_meta_data->>'avatar_url'
from auth.users
on conflict (user_id) do nothing;

insert into public.wallet_categories(user_id, name)
select u.id, c.category
from auth.users u
cross join unnest(array['饮食','交通','购物','居住','娱乐','医疗','教育','投资','旅游','其他']) as c(category)
on conflict (user_id, name) do nothing;

-- WY Wallet Mobile: multi-user schema isolated from the existing Streamlit tables.
-- Safe to run in the same Supabase project: it creates only wallet_* objects.

create extension if not exists pgcrypto;

create table if not exists public.wallet_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  email text,
  avatar_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.wallet_categories (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  name text not null check (length(trim(name)) between 1 and 60),
  created_at timestamptz not null default now(),
  unique (user_id, name)
);

create table if not exists public.wallet_transactions (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  date date not null default current_date,
  item text not null check (length(trim(item)) between 1 and 180),
  category text not null default '其他',
  type text not null default 'Expense' check (type in ('Expense', 'Income')),
  amount numeric(14,2) not null check (amount > 0),
  note text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists wallet_transactions_user_date_idx
  on public.wallet_transactions(user_id, date desc, created_at desc);
create index if not exists wallet_transactions_user_category_idx
  on public.wallet_transactions(user_id, category);

alter table public.wallet_profiles enable row level security;
alter table public.wallet_categories enable row level security;
alter table public.wallet_transactions enable row level security;

